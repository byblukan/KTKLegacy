#!/usr/bin/env python3
"""
Generates src/core/trustanchors.c - the BearSSL trust anchors the client accepts - from the PEM
files in certs/.

A BearSSL trust anchor is only a distinguished name and a public key, so a cross-signed
certificate works as well as the self-signed root: certs/root-ye.pem is "ISRG Root YE" as the
site sends it (signed by ISRG Root X2), and only its subject and key are used.

The site's chain (checked 2026-11-07): leaf (P-256) -> Let's Encrypt YE2 -> ISRG Root YE ->
ISRG Root X2 -> ISRG Root X1. Any one of these anchors is enough; all three are kept so the
client keeps working when Let's Encrypt changes which root it presents.

Usage: python3 tools/gen-trust-anchors.py   (from the project directory; needs `cryptography`)
"""

import glob
import os
import sys

from cryptography import x509
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'core', 'trustanchors.c')

CURVES = {'secp256r1': 'BR_EC_secp256r1', 'secp384r1': 'BR_EC_secp384r1', 'secp521r1': 'BR_EC_secp521r1'}


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 12):
        lines.append('\t' + ', '.join('0x%02X' % b for b in data[i:i + 12]) + ',')
    return '\n'.join(lines)


def int_bytes(n):
    return n.to_bytes((n.bit_length() + 7) // 8, 'big')


def main():
    certs = []
    seen = set()
    for path in sorted(glob.glob(os.path.join(ROOT, 'certs', '*.pem'))):
        with open(path, 'rb') as f:
            for cert in x509.load_pem_x509_certificates(f.read()):
                dn = cert.subject.public_bytes()
                if dn in seen:
                    continue
                seen.add(dn)
                certs.append(cert)

    out = ['/* Generated by tools/gen-trust-anchors.py from the PEM files in certs/ - do not edit.',
           ' * Plain assignments rather than designated initializers, so the file compiles the same',
           ' * as C89 or C++ with any toolchain (GCCE 4.4 included). */',
           '#include "trustanchors.h"', '']
    setup = []
    for i, cert in enumerate(certs):
        name = cert.subject.rfc4514_string()
        out.append('/* %s */' % name)
        out.append('static const unsigned char TA%d_DN[] = {' % i)
        out.append(c_bytes(cert.subject.public_bytes()))
        out.append('};')
        setup.append('\t/* %s */' % name)
        setup.append('\tKTK_TRUST_ANCHORS[%d].dn.data = (unsigned char *)TA%d_DN;' % (i, i))
        setup.append('\tKTK_TRUST_ANCHORS[%d].dn.len = sizeof TA%d_DN;' % (i, i))
        setup.append('\tKTK_TRUST_ANCHORS[%d].flags = BR_X509_TA_CA;' % i)
        key = cert.public_key()
        if isinstance(key, rsa.RSAPublicKey):
            numbers = key.public_numbers()
            out.append('static const unsigned char TA%d_RSA_N[] = {' % i)
            out.append(c_bytes(int_bytes(numbers.n)))
            out.append('};')
            out.append('static const unsigned char TA%d_RSA_E[] = {' % i)
            out.append(c_bytes(int_bytes(numbers.e)))
            out.append('};')
            setup.append('\tKTK_TRUST_ANCHORS[%d].pkey.key_type = BR_KEYTYPE_RSA;' % i)
            setup.append('\tKTK_TRUST_ANCHORS[%d].pkey.key.rsa.n = (unsigned char *)TA%d_RSA_N;' % (i, i))
            setup.append('\tKTK_TRUST_ANCHORS[%d].pkey.key.rsa.nlen = sizeof TA%d_RSA_N;' % (i, i))
            setup.append('\tKTK_TRUST_ANCHORS[%d].pkey.key.rsa.e = (unsigned char *)TA%d_RSA_E;' % (i, i))
            setup.append('\tKTK_TRUST_ANCHORS[%d].pkey.key.rsa.elen = sizeof TA%d_RSA_E;' % (i, i))
        elif isinstance(key, ec.EllipticCurvePublicKey):
            curve = CURVES.get(key.curve.name)
            if curve is None:
                sys.exit('unsupported curve %s in %s' % (key.curve.name, name))
            q = key.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
            out.append('static const unsigned char TA%d_EC_Q[] = {' % i)
            out.append(c_bytes(q))
            out.append('};')
            setup.append('\tKTK_TRUST_ANCHORS[%d].pkey.key_type = BR_KEYTYPE_EC;' % i)
            setup.append('\tKTK_TRUST_ANCHORS[%d].pkey.key.ec.curve = %s;' % (i, curve))
            setup.append('\tKTK_TRUST_ANCHORS[%d].pkey.key.ec.q = (unsigned char *)TA%d_EC_Q;' % (i, i))
            setup.append('\tKTK_TRUST_ANCHORS[%d].pkey.key.ec.qlen = sizeof TA%d_EC_Q;' % (i, i))
        else:
            sys.exit('unsupported key type in %s' % name)
        out.append('')

    out.append('br_x509_trust_anchor KTK_TRUST_ANCHORS[%d];' % len(certs))
    out.append('const size_t KTK_TRUST_ANCHORS_NUM = %d;' % len(certs))
    out.append('')
    out.append('void ktk_trust_anchors_init(void)')
    out.append('{')
    out.append('\tstatic int done = 0;')
    out.append('\tif (done) {')
    out.append('\t\treturn;')
    out.append('\t}')
    out.extend(setup)
    out.append('\tdone = 1;')
    out.append('}')
    out.append('')
    anchors = certs
    with open(OUT, 'w') as f:
        f.write('\n'.join(out))
    print('wrote %d trust anchors to %s' % (len(anchors), os.path.relpath(OUT, ROOT)))
    for cert in certs:
        print('  ' + cert.subject.rfc4514_string())


if __name__ == '__main__':
    main()
